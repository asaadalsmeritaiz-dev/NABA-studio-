import fs from 'node:fs';
import path from 'node:path';
import { GoogleGenAI } from '@google/genai';
import type { ClassroomEnvironment, Lecturer, SceneRecord } from '../../src/types/studio.ts';
import { hasGeminiApiKey, probeMediaDuration } from './geminiProvider.ts';
import type { LipSyncRequest, LipSyncResult } from './types.ts';
import { isValidMp4Buffer, validateExternalEndpointUrl } from '../services/security.ts';
import { logEvent } from '../services/logger.ts';

export interface LecturerVideoRequest {
  lecturer: Lecturer;
  lecturerImagePath: string;
  environment: ClassroomEnvironment;
  scene: SceneRecord;
  language: 'ar' | 'en';
  targetDurationSec: number;
  outputVideoPath: string;
  allowPaidVideoGen: boolean;
}

export interface LecturerVideoResult {
  status: 'generated' | 'not_configured' | 'failed';
  provider: string;
  videoPath?: string;
  durationSec?: number;
  reason: string;
}

export function isPaidGeminiModelsEnabled(): boolean {
  return process.env.ENABLE_PAID_GEMINI_MODELS?.trim().toLowerCase() === 'true' && hasGeminiApiKey();
}

export function verifyLecturerConsent(lecturer: Lecturer, lecturerImagePath: string | null): {
  ok: boolean;
  reason?: string;
} {
  if (!lecturer.consent_verified) {
    return {
      ok: false,
      reason: 'Lecturer likeness consent is not verified. Video synthesis is blocked.',
    };
  }
  if (!lecturerImagePath || !fs.existsSync(lecturerImagePath)) {
    return {
      ok: false,
      reason: 'Lecturer reference portrait file is missing on disk.',
    };
  }
  return { ok: true };
}

function detectImageMimeType(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  if (ext === '.png') return 'image/png';
  if (ext === '.webp') return 'image/webp';
  return 'image/jpeg';
}

/**
 * Real provider-based lip-sync adapter (SadTalker / MuseTalk / HeyGen).
 * Enforces SSRF protection and verifies genuine MP4 video stream output.
 * Never claims static transitions are facial animation.
 */
export async function runLipSyncAdapter(req: LipSyncRequest): Promise<LipSyncResult> {
  const sadTalkerUrl = process.env.SADTALKER_ENDPOINT?.trim();
  const museTalkUrl = process.env.MUSETALK_ENDPOINT?.trim();
  const heygenKey = process.env.HEYGEN_API_KEY?.trim();

  if (sadTalkerUrl || museTalkUrl) {
    const endpoint = sadTalkerUrl || museTalkUrl || '';
    const providerName = sadTalkerUrl ? 'sadtalker-gpu-worker' : 'musetalk-gpu-worker';

    const urlCheck = validateExternalEndpointUrl(endpoint, { allowLoopbackForTest: true });
    if (!urlCheck.ok) {
      logEvent('warn', 'lipsync_url_blocked', { provider: providerName, error: urlCheck.error });
      return {
        supported: false,
        provider: providerName,
        reason: `Lip-sync endpoint rejected: ${urlCheck.error}`,
      };
    }

    try {
      const formData = new FormData();
      formData.append('source_image', new Blob([fs.readFileSync(req.lecturerImagePath)]), 'lecturer.jpg');
      formData.append('driven_audio', new Blob([fs.readFileSync(req.audioWavPath)]), 'narration.wav');

      const res = await fetch(urlCheck.url.toString(), {
        method: 'POST',
        body: formData,
        signal: AbortSignal.timeout(90_000),
      });

      if (!res.ok) {
        return {
          supported: false,
          provider: providerName,
          reason: `External lip-sync worker (${providerName}) returned HTTP ${res.status}.`,
        };
      }

      const buf = Buffer.from(await res.arrayBuffer());
      if (!isValidMp4Buffer(buf)) {
        return {
          supported: false,
          provider: providerName,
          reason: `Lip-sync worker (${providerName}) did not return a valid MP4 video stream.`,
        };
      }

      fs.mkdirSync(path.dirname(req.outputVideoPath), { recursive: true });
      fs.writeFileSync(req.outputVideoPath, buf);
      const dur = await probeMediaDuration(req.outputVideoPath);
      if (dur <= 0) {
        fs.rmSync(req.outputVideoPath, { force: true });
        return {
          supported: false,
          provider: providerName,
          reason: `Lip-sync output from ${providerName} failed ffprobe media verification.`,
        };
      }

      return {
        supported: true,
        provider: providerName,
        videoPath: req.outputVideoPath,
        reason: `Synchronized facial lip-sync clip (${dur.toFixed(1)}s) generated by ${providerName}.`,
      };
    } catch (err) {
      return {
        supported: false,
        provider: providerName,
        reason: `Lip-sync worker unreachable: ${err instanceof Error ? err.message : 'network error'}`,
      };
    }
  }

  if (heygenKey) {
    return {
      supported: false,
      provider: 'heygen-api',
      reason:
        'HEYGEN_API_KEY detected, but an avatar_id mapping and async HeyGen webhook callback are required before dispatching paid avatar renders.',
    };
  }

  return {
    supported: false,
    provider: 'not_configured',
    reason:
      'Provider Not Configured: Set SADTALKER_ENDPOINT or MUSETALK_ENDPOINT for real facial lip-sync. Preserving deterministic smartboard Presenter PiP.',
  };
}

/**
 * Real provider-based generative lecturer video engine.
 * Supports:
 * 1. Self-hosted GPU endpoints (WAN_VIDEO_ENDPOINT / LTX_VIDEO_ENDPOINT) with SSRF & MP4 verification.
 * 2. Gemini Omni Flash (`gemini-omni-1.2-flash`) via verified Interactions API (`ai.interactions.create`),
 *    strictly gated behind explicit opt-in (`ENABLE_PAID_GEMINI_MODELS=true` + `allowPaidVideoGen=true`).
 */
export async function generateLecturerSceneVideo(
  req: LecturerVideoRequest,
): Promise<LecturerVideoResult> {
  const consentCheck = verifyLecturerConsent(req.lecturer, req.lecturerImagePath);
  if (!consentCheck.ok) {
    return {
      status: 'failed',
      provider: 'consent-gate',
      reason: consentCheck.reason ?? 'Consent verification failed.',
    };
  }

  const wanEndpoint = process.env.WAN_VIDEO_ENDPOINT?.trim();
  const ltxEndpoint = process.env.LTX_VIDEO_ENDPOINT?.trim();

  // Adapter 1: External open-weights GPU worker (Wan 2.1 / LTX-Video)
  if (wanEndpoint || ltxEndpoint) {
    const endpoint = wanEndpoint || ltxEndpoint || '';
    const providerKey = wanEndpoint ? 'wan-2.1-gpu-worker' : 'ltx-video-gpu-worker';
    const urlCheck = validateExternalEndpointUrl(endpoint, { allowLoopbackForTest: true });
    if (!urlCheck.ok) {
      return {
        status: 'failed',
        provider: providerKey,
        reason: `Generative video endpoint rejected: ${urlCheck.error}`,
      };
    }

    try {
      const prompt = buildLecturerPrompt(req);
      const formData = new FormData();
      formData.append(
        'reference_image',
        new Blob([fs.readFileSync(req.lecturerImagePath)], { type: detectImageMimeType(req.lecturerImagePath) }),
        path.basename(req.lecturerImagePath),
      );
      formData.append('prompt', prompt);
      formData.append('duration_sec', String(Math.max(3, Math.min(15, Math.round(req.targetDurationSec)))));

      const res = await fetch(urlCheck.url.toString(), {
        method: 'POST',
        body: formData,
        signal: AbortSignal.timeout(180_000),
      });

      if (!res.ok) {
        return {
          status: 'failed',
          provider: providerKey,
          reason: `Video provider ${providerKey} returned HTTP ${res.status}.`,
        };
      }

      const buf = Buffer.from(await res.arrayBuffer());
      if (!isValidMp4Buffer(buf)) {
        return {
          status: 'failed',
          provider: providerKey,
          reason: `Video provider ${providerKey} did not return a valid MP4 binary.`,
        };
      }

      fs.mkdirSync(path.dirname(req.outputVideoPath), { recursive: true });
      fs.writeFileSync(req.outputVideoPath, buf);
      const durationSec = await probeMediaDuration(req.outputVideoPath);
      if (durationSec <= 0) {
        fs.rmSync(req.outputVideoPath, { force: true });
        return {
          status: 'failed',
          provider: providerKey,
          reason: `Video returned by ${providerKey} could not be decoded by ffprobe.`,
        };
      }

      return {
        status: 'generated',
        provider: providerKey,
        videoPath: req.outputVideoPath,
        durationSec,
        reason: `Playable lecturer video clip (${durationSec.toFixed(1)}s) generated via ${providerKey}.`,
      };
    } catch (err) {
      return {
        status: 'failed',
        provider: providerKey,
        reason: `Video provider ${providerKey} failed: ${err instanceof Error ? err.message : 'network error'}`,
      };
    }
  }

  // Adapter 2: Verified Gemini Omni Flash (`gemini-omni-1.2-flash`) via Interactions API
  // Strictly requires explicit server enablement AND explicit per-request user opt-in (never silent paid invocation).
  if (req.allowPaidVideoGen && isPaidGeminiModelsEnabled()) {
    try {
      const apiKey = process.env.GEMINI_API_KEY?.trim() ?? '';
      const ai = new GoogleGenAI({
        apiKey,
        httpOptions: {
          headers: {
            'User-Agent': 'aistudio-build',
          },
        },
      });

      const imageBytes = fs.readFileSync(req.lecturerImagePath).toString('base64');
      const mimeType = detectImageMimeType(req.lecturerImagePath);
      const clampedSec = Math.max(3, Math.min(10, Math.round(req.targetDurationSec)));

      const interaction = await (ai as unknown as {
        interactions: {
          create: (
            params: Record<string, unknown>,
            opts?: Record<string, unknown>,
          ) => Promise<{ output_video?: { data?: string; mime_type?: string } }>;
        };
      }).interactions.create(
        {
          model: 'gemini-omni-1.2-flash',
          input: [
            {
              type: 'image',
              mime_type: mimeType,
              data: imageBytes,
            },
            {
              type: 'text',
              text: buildLecturerPrompt(req),
            },
          ],
          background: false,
          store: false,
          stream: false,
          response_format: {
            type: 'video',
            aspect_ratio: '16:9',
            duration: `${clampedSec}s`,
            resolution: '720p',
          },
        },
        { timeout: 300_000 },
      );

      const videoBase64 = interaction?.output_video?.data;
      if (!videoBase64) {
        return {
          status: 'failed',
          provider: 'gemini-omni-1.2-flash',
          reason: 'Gemini Omni Flash completed without returning playable video data.',
        };
      }

      const videoBuf = Buffer.from(videoBase64, 'base64');
      if (!isValidMp4Buffer(videoBuf)) {
        return {
          status: 'failed',
          provider: 'gemini-omni-1.2-flash',
          reason: 'Gemini Omni Flash response failed MP4 container validation.',
        };
      }

      fs.mkdirSync(path.dirname(req.outputVideoPath), { recursive: true });
      fs.writeFileSync(req.outputVideoPath, videoBuf);
      const durationSec = await probeMediaDuration(req.outputVideoPath);
      if (durationSec <= 0) {
        fs.rmSync(req.outputVideoPath, { force: true });
        return {
          status: 'failed',
          provider: 'gemini-omni-1.2-flash',
          reason: 'Generated video failed ffprobe duration verification.',
        };
      }

      return {
        status: 'generated',
        provider: 'gemini-omni-1.2-flash',
        videoPath: req.outputVideoPath,
        durationSec,
        reason: `Playable lecturer clip (${durationSec.toFixed(1)}s) generated via Gemini Omni Flash.`,
      };
    } catch (err) {
      return {
        status: 'failed',
        provider: 'gemini-omni-1.2-flash',
        reason: `Gemini Omni Flash error: ${err instanceof Error ? err.message : 'unknown error'}`,
      };
    }
  }

  return {
    status: 'not_configured',
    provider: 'not_configured',
    reason:
      'Provider Not Configured: Configure WAN_VIDEO_ENDPOINT, LTX_VIDEO_ENDPOINT, or enable paid Gemini Omni Flash (ENABLE_PAID_GEMINI_MODELS=true with explicit approval). Preserving deterministic smartboard rendering.',
  };
}

function buildLecturerPrompt(req: LecturerVideoRequest): string {
  return [
    `Maintain the exact facial identity, clothing, and professional academic posture of the lecturer shown in the reference portrait (${req.lecturer.name}).`,
    `Classroom environment: ${req.environment.name} — ${req.environment.description}.`,
    `Educational scene context: "${req.scene.title}". ${req.scene.visual_instructions || ''}`,
    `Natural, calm university instructor head movements, subtle eye contact with the camera, and composed academic hand gestures suitable for a ${req.language === 'ar' ? 'Modern Standard Arabic' : 'English'} lecture.`,
    'Do not render text overlays or subtitles inside the video frame; smartboard text and code are composited deterministically.',
  ]
    .filter(Boolean)
    .join(' ');
}
